export type I18nKey = keyof typeof ZH_TW;

export function t(
  key: I18nKey,
  params: Record<string, string | number> = {}
): string {
  let value = ZH_TW[key];

  for (const [name, replacement] of Object.entries(params)) {
    value = value.replace(`{${name}}`, String(replacement)) as typeof value;
  }

  return value;
}
